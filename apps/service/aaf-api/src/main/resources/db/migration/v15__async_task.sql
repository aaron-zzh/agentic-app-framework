CREATE TABLE sys_async_task (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version        INTEGER      NOT NULL DEFAULT 0,
    org_id         BIGINT,
    workspace_id   BIGINT,
    task_id        VARCHAR(64)  NOT NULL UNIQUE,
    task_type      VARCHAR(100) NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    payload        TEXT         NOT NULL DEFAULT '{}',
    result         TEXT,
    priority       SMALLINT     NOT NULL DEFAULT 5,
    max_retries    INTEGER      NOT NULL DEFAULT 3,
    attempt_count  INTEGER      NOT NULL DEFAULT 0,
    last_error     TEXT,
    started_at     TIMESTAMP(6),
    completed_at   TIMESTAMP(6),
    create_by      BIGINT,
    create_by_type VARCHAR(16),
    create_time    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_by_type VARCHAR(16),
    update_time    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    owner_id       BIGINT       NOT NULL,
    delete_time    TIMESTAMP(6),
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    remark         VARCHAR(255),
    CONSTRAINT ck_async_task_status CHECK (status IN ('PENDING', 'QUEUED', 'RUNNING', 'RETRY_WAIT', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_async_task_priority CHECK (priority BETWEEN 0 AND 9),
    CONSTRAINT ck_async_task_retry CHECK (max_retries >= 0 AND attempt_count >= 0)
);

COMMENT ON TABLE sys_async_task IS '通用异步任务主记录，承载用户可查询的逻辑任务生命周期';
COMMENT ON COLUMN sys_async_task.task_id IS '与 Redis Stream AsyncTaskMessage.id 相同的稳定任务 ID';
COMMENT ON COLUMN sys_async_task.payload IS '提交时的业务输入快照；Redis Stream 仅作为投递载体';
COMMENT ON COLUMN sys_async_task.result IS '任务成功后的业务结果摘要';

CREATE INDEX idx_async_task_owner_create_time ON sys_async_task (owner_id, create_time DESC);
CREATE INDEX idx_async_task_status_create_time ON sys_async_task (status, create_time DESC);
CREATE INDEX idx_async_task_scope_create_time ON sys_async_task (org_id, workspace_id, create_time DESC);

