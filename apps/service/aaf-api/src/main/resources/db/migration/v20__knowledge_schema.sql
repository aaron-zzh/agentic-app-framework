CREATE OR REPLACE FUNCTION validate_ai_knowledge_assertion_attributes_v20(
    checked_attributes JSONB)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
    SELECT jsonb_typeof(checked_attributes) = 'object'
       AND octet_length(convert_to(checked_attributes::text, 'UTF8')) <= 16384
       AND (SELECT COUNT(*) FROM jsonb_object_keys(checked_attributes)) <= 64
       AND NOT EXISTS (
           SELECT 1
           FROM jsonb_each(checked_attributes) attribute
           WHERE attribute.key !~ '^[A-Za-z][A-Za-z0-9_.-]{0,63}$'
              OR attribute.key IN (
                  'assertionId', 'factId', 'evidenceId', 'validAt', 'invalidAt',
                  'recordedAt', 'expiredAt', 'expirationReason', 'referenceTime',
                  'knowledgeBaseId', 'documentId', 'sourceId', 'runId')
              OR jsonb_typeof(attribute.value) NOT IN ('string', 'number', 'boolean', 'array')
              OR (jsonb_typeof(attribute.value) = 'array' AND EXISTS (
                  SELECT 1
                  FROM jsonb_array_elements(attribute.value) item
                  WHERE jsonb_typeof(item) NOT IN ('string', 'number', 'boolean')
              ))
       );
$$;

