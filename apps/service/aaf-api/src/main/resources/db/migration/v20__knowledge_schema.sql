CREATE OR REPLACE FUNCTION check_ai_knowledge_generation_consistency_v20(
    checked_document_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    active_run UUID;
    published_count BIGINT;
    matching_count BIGINT;
BEGIN
    SELECT document.active_run_id
    INTO active_run
    FROM ai_knowledge_document document
    WHERE document.id = checked_document_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COUNT(*),
           COUNT(*) FILTER (WHERE run.id IS NOT DISTINCT FROM active_run)
    INTO published_count, matching_count
    FROM ai_knowledge_ingest_run run
    WHERE run.document_id = checked_document_id
      AND run.status = 'PUBLISHED';

    IF active_run IS NULL AND published_count <> 0 THEN
        RAISE EXCEPTION
            'document % 没有 active_run_id，但存在 % 个 PUBLISHED run',
            checked_document_id, published_count;
    END IF;
    IF active_run IS NOT NULL
       AND (published_count <> 1 OR matching_count <> 1) THEN
        RAISE EXCEPTION
            'document % 的 active_run_id % 与 PUBLISHED run 不一致',
            checked_document_id, active_run;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM ai_knowledge_fact_evidence assertion
        JOIN ai_knowledge_evidence evidence ON evidence.id = assertion.evidence_id
        JOIN ai_knowledge_ingest_run run ON run.id = evidence.run_id
        WHERE evidence.document_id = checked_document_id
          AND (
              (run.status IN ('QUEUED', 'PROCESSING', 'READY', 'FAILED')
               AND (assertion.recorded_at IS NOT NULL
                    OR assertion.expired_at IS NOT NULL
                    OR assertion.expiration_reason IS NOT NULL))
              OR (run.status = 'PUBLISHED' AND assertion.recorded_at IS NULL)
              OR (run.status = 'SUPERSEDED'
                  AND (assertion.recorded_at IS NULL
                       OR assertion.expired_at IS NULL
                       OR assertion.expiration_reason IS NULL))
          )
    ) THEN
        RAISE EXCEPTION 'document % 存在与 run 状态不一致的断言时间', checked_document_id;
    END IF;
END;
$$;

-- 延迟触发器每次按事务最终状态检查；不得缓存结果，否则 SET CONSTRAINTS 后的继续写入可能绕过提交校验。
CREATE OR REPLACE FUNCTION check_ai_knowledge_assertion_v20(
    checked_assertion_id UUID)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    assertion_row RECORD;
BEGIN
    SELECT run.status, assertion.recorded_at, assertion.expired_at,
           assertion.expiration_reason
    INTO assertion_row
    FROM ai_knowledge_fact_evidence assertion
    JOIN ai_knowledge_evidence evidence ON evidence.id = assertion.evidence_id
    JOIN ai_knowledge_ingest_run run ON run.id = evidence.run_id
    WHERE assertion.assertion_id = checked_assertion_id;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    IF (assertion_row.status IN ('QUEUED', 'PROCESSING', 'READY', 'FAILED')
        AND (assertion_row.recorded_at IS NOT NULL
             OR assertion_row.expired_at IS NOT NULL
             OR assertion_row.expiration_reason IS NOT NULL))
       OR (assertion_row.status = 'PUBLISHED'
           AND assertion_row.recorded_at IS NULL)
       OR (assertion_row.status = 'SUPERSEDED'
           AND (assertion_row.recorded_at IS NULL
                OR assertion_row.expired_at IS NULL
                OR assertion_row.expiration_reason IS NULL)) THEN
        RAISE EXCEPTION 'assertion % 与 run 状态 % 不一致',
            checked_assertion_id, assertion_row.status;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_ai_knowledge_document_generation_v20()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM check_ai_knowledge_generation_consistency_v20(NEW.id);
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_ai_knowledge_run_generation_v20()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM check_ai_knowledge_generation_consistency_v20(OLD.document_id);
    ELSIF TG_OP = 'UPDATE' THEN
        PERFORM check_ai_knowledge_generation_consistency_v20(OLD.document_id);
        IF NEW.document_id IS DISTINCT FROM OLD.document_id THEN
            PERFORM check_ai_knowledge_generation_consistency_v20(NEW.document_id);
        END IF;
    ELSE
        PERFORM check_ai_knowledge_generation_consistency_v20(NEW.document_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_ai_knowledge_assertion_generation_v20()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM check_ai_knowledge_assertion_v20(
        CASE WHEN TG_OP = 'DELETE' THEN OLD.assertion_id ELSE NEW.assertion_id END);
    RETURN NULL;
END;
$$;

