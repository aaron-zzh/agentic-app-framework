-- ============================================================
-- 通用设备层 module/device Schema
-- 设备配对、认证、MQTT 通道与下行消息；与具体业务场景无关。
-- 同一序列号仅允许一条 BOUND 记录；解绑记录保留审计，重新配对创建新记录与新凭据。
-- ============================================================

-- ==================== 设备 device_info ====================

CREATE TABLE device_info (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version                   INTEGER      NOT NULL DEFAULT 0,
    org_id                    BIGINT,
    workspace_id              BIGINT,
    serial_number             VARCHAR(100) NOT NULL,
    device_key                VARCHAR(100) NOT NULL,
    name                      VARCHAR(100) NOT NULL,
    model                     VARCHAR(100),
    firmware_version          VARCHAR(64),
    device_type               VARCHAR(32)  NOT NULL,
    zone                      VARCHAR(32)  NOT NULL DEFAULT 'OTHER',
    scenario_key              VARCHAR(64)  NOT NULL,
    subject_type              VARCHAR(128),
    subject_id                BIGINT,
    role_key                  VARCHAR(128),
    owner_user_id             BIGINT       NOT NULL,
    credential_hash           VARCHAR(128) NOT NULL,
    credential_prefix         VARCHAR(32)  NOT NULL,
    status                    VARCHAR(16)  NOT NULL DEFAULT 'BOUND',
    online_status             VARCHAR(16)  NOT NULL DEFAULT 'OFFLINE',
    boot_id                   VARCHAR(100),
    boot_started_at           TIMESTAMP(6),
    status_sequence           BIGINT       NOT NULL DEFAULT 0,
    last_heartbeat_at         TIMESTAMP(6),
    last_person_seen_at       TIMESTAMP(6),
    camera_status             VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN',
    privacy_mode              BOOLEAN      NOT NULL DEFAULT FALSE,
    capabilities              JSONB        NOT NULL DEFAULT '{}'::jsonb,
    credential_revoked_at     TIMESTAMP(6),
    credential_last_used_at   TIMESTAMP(6),
    owner_id                  BIGINT,
    create_by                 BIGINT,
    create_by_type            VARCHAR(16),
    create_time               TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by                 BIGINT,
    update_by_type            VARCHAR(16),
    update_time               TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time               TIMESTAMP(6),
    deleted                   BOOLEAN      NOT NULL DEFAULT FALSE,
    remark                    VARCHAR(255)
);

COMMENT ON TABLE device_info IS '通用设备与场景主体绑定';
COMMENT ON COLUMN device_info.scenario_key IS '设备业务场景稳定键';
COMMENT ON COLUMN device_info.subject_type IS '场景主体资源键';
COMMENT ON COLUMN device_info.subject_id IS '场景主体记录 ID';
COMMENT ON COLUMN device_info.role_key IS '设备级角色覆盖编码';
COMMENT ON COLUMN device_info.owner_user_id IS '设备所有者用户 ID，同时作为计费主体';
COMMENT ON COLUMN device_info.credential_hash IS '设备凭据 SHA-256 哈希，不保存明文';
COMMENT ON COLUMN device_info.boot_started_at IS '当前 bootId 的设备启动时间，用于拒绝旧启动延迟消息';
COMMENT ON COLUMN device_info.status_sequence IS '当前 bootId 内单调递增的状态序号';

CREATE UNIQUE INDEX uk_device_info_serial_bound
    ON device_info(serial_number)
    WHERE deleted = FALSE AND status = 'BOUND';
CREATE UNIQUE INDEX uk_device_info_key
    ON device_info(device_key) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_device_info_credential_hash
    ON device_info(credential_hash) WHERE deleted = FALSE;
CREATE INDEX idx_device_info_scenario_subject_status
    ON device_info(scenario_key, subject_id, status) WHERE deleted = FALSE;
CREATE INDEX idx_device_info_owner
    ON device_info(owner_user_id) WHERE deleted = FALSE;
CREATE INDEX idx_device_info_online_heartbeat
    ON device_info(online_status, last_heartbeat_at) WHERE deleted = FALSE;

-- ==================== 设备下行消息 device_message ====================

CREATE TABLE device_message (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER      NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    device_id         BIGINT       NOT NULL,
    command_id        VARCHAR(100) NOT NULL,
    message_id        VARCHAR(100) NOT NULL,
    direction         VARCHAR(16)  NOT NULL,
    capability        VARCHAR(100) NOT NULL,
    action            VARCHAR(64)  NOT NULL,
    payload           JSONB        NOT NULL DEFAULT '{}'::jsonb,
    status            VARCHAR(24)  NOT NULL DEFAULT 'QUEUED',
    correlation_id    VARCHAR(100),
    trace_id          VARCHAR(100),
    payload_hash      VARCHAR(128) NOT NULL,
    sequence_no       BIGINT       NOT NULL,
    issued_at         TIMESTAMP(6) NOT NULL,
    expires_at        TIMESTAMP(6) NOT NULL,
    dispatched_at     TIMESTAMP(6),
    accepted_at       TIMESTAMP(6),
    completed_at      TIMESTAMP(6),
    result            JSONB,
    failure_reason    VARCHAR(500),
    owner_id          BIGINT,
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255),
    CONSTRAINT ck_device_message_expiry CHECK (expires_at > issued_at)
);

COMMENT ON TABLE device_message IS '设备可靠下行消息与 MQTT outbox';
COMMENT ON COLUMN device_message.direction IS 'COMMAND/CANCEL/CONFIG';
COMMENT ON COLUMN device_message.status IS 'QUEUED/DISPATCHED/ACCEPTED/SUCCEEDED/FAILED/EXPIRED/CANCELLED/DELIVERY_UNKNOWN';
COMMENT ON COLUMN device_message.payload_hash IS '同一 commandId 内容一致性校验哈希';

CREATE UNIQUE INDEX uk_device_message_command
    ON device_message(command_id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_device_message_message
    ON device_message(message_id) WHERE deleted = FALSE;
CREATE UNIQUE INDEX uk_device_message_sequence
    ON device_message(device_id, sequence_no) WHERE deleted = FALSE;
CREATE INDEX idx_device_message_dispatch
    ON device_message(status, issued_at)
    WHERE deleted = FALSE AND status IN ('QUEUED', 'DELIVERY_UNKNOWN');
CREATE INDEX idx_device_message_expiry
    ON device_message(expires_at)
    WHERE deleted = FALSE AND status IN ('QUEUED', 'DISPATCHED', 'ACCEPTED');
