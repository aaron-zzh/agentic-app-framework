-- ============================================================
-- autodev 子域（从 v1 迁移至此，并新增 autodev_session）
-- ============================================================

CREATE TABLE autodev_request (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         INTEGER      NOT NULL DEFAULT 0,
    org_id          BIGINT,
    workspace_id    BIGINT,
    requirement     TEXT         NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'pending',
    planning_result JSONB,
    review_result   JSONB,
    completed_at    TIMESTAMP(6),
    archived_at     TIMESTAMP(6),
    create_by       BIGINT,
    create_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time     TIMESTAMP(6),
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    remark          VARCHAR(255)
);

COMMENT ON TABLE autodev_request IS 'AI 代码生成请求';

CREATE TABLE autodev_generated_code (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT,
    workspace_id BIGINT,
    request_id   BIGINT       NOT NULL REFERENCES autodev_request(id),
    file_path    VARCHAR(500) NOT NULL,
    content      TEXT         NOT NULL,
    archived_at  TIMESTAMP(6),
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE autodev_generated_code IS 'AI 生成的代码文件';

CREATE TABLE autodev_execution_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT,
    workspace_id BIGINT,
    request_id   BIGINT,
    source       VARCHAR(50)  NOT NULL,
    agent        VARCHAR(50),
    input        TEXT,
    output       TEXT,
    status       VARCHAR(20)  NOT NULL DEFAULT 'running',
    duration_ms  BIGINT,
    archived_at  TIMESTAMP(6),
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE autodev_execution_log IS 'Agent 执行日志';

-- autodev_session：Kiro Agent 会话记录（AAF-020 新增）
CREATE TABLE autodev_session (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version       INTEGER      NOT NULL DEFAULT 0,
    org_id        BIGINT,
    workspace_id  BIGINT,
    session_id    VARCHAR(64)  NOT NULL,
    agent_role    VARCHAR(50)  NOT NULL DEFAULT 'kiro_default',
    status        VARCHAR(20)  NOT NULL DEFAULT 'active',
    user_id       BIGINT       NOT NULL DEFAULT 0,
    -- 关联的开发文档 ID 列表（会话中涉及的文档）
    related_doc_ids  BIGINT[],
    -- 关联的源码文件路径列表
    related_file_paths TEXT[],
    create_by     BIGINT,
    create_time   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by     BIGINT,
    update_time   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time   TIMESTAMP(6),
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    remark        VARCHAR(255)
);

COMMENT ON TABLE autodev_session IS 'Kiro Agent 执行会话';
COMMENT ON COLUMN autodev_session.related_doc_ids IS '会话中涉及的开发文档 ID 列表';
COMMENT ON COLUMN autodev_session.related_file_paths IS '会话中涉及的源码文件路径列表';
CREATE INDEX idx_autodev_session_user ON autodev_session(user_id);
CREATE INDEX idx_autodev_session_status ON autodev_session(status);

-- autodev_message：Kiro Agent 对话消息记录
CREATE TABLE autodev_message (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL REFERENCES autodev_session(id) ON DELETE CASCADE,
    -- 消息角色：user / assistant / system
    role         VARCHAR(20)  NOT NULL DEFAULT 'user',
    content      TEXT         NOT NULL,
    -- 行动者类型：human / kiro / ai
    actor_type   VARCHAR(20)  NOT NULL DEFAULT 'human',
    -- 该消息关联产生/修改的开发文档
    doc_id       BIGINT       REFERENCES autodev_doc(id),
    -- 该消息关联的源码文件路径
    file_path    VARCHAR(500),
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE autodev_message IS 'Kiro Agent 对话消息（含用户输入、AI回复、关联产物）';
COMMENT ON COLUMN autodev_message.actor_type IS 'human（用户输入）/ kiro（kiro-cli 输出）/ ai（AI 回复）';
COMMENT ON COLUMN autodev_message.doc_id IS '该消息关联产生或修改的开发文档';
COMMENT ON COLUMN autodev_message.file_path IS '该消息关联的源码文件路径';
CREATE INDEX idx_autodev_message_session ON autodev_message(session_id);
CREATE INDEX idx_autodev_message_doc ON autodev_message(doc_id) WHERE doc_id IS NOT NULL;
CREATE INDEX idx_autodev_message_file ON autodev_message(file_path) WHERE file_path IS NOT NULL;


-- autodev_doc：开发文档同步表（docs/ 目录镜像，AAF-020 新增）
-- 与 doc_document（业务文档）分离，专属 aaf-auto-dev 模块管理
CREATE TABLE autodev_doc (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT,
    workspace_id BIGINT,
    title        VARCHAR(200) NOT NULL,
    file_path    VARCHAR(500) NOT NULL UNIQUE,
    content      TEXT,
    doc_type     VARCHAR(50)  NOT NULL DEFAULT 'spec',
    front_matter JSONB,
    status       VARCHAR(20)  NOT NULL DEFAULT 'active',
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE autodev_doc IS '开发文档（docs/ 目录同步，协作开发专用）';
COMMENT ON COLUMN autodev_doc.front_matter IS 'Front Matter 元数据（YAML 解析后的 JSON）';

CREATE INDEX idx_autodev_doc_fts
    ON autodev_doc USING GIN (to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(content, '')));

-- autodev_doc_link：开发文档引用关系
CREATE TABLE autodev_doc_link (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id   BIGINT NOT NULL REFERENCES autodev_doc(id) ON DELETE CASCADE,
    target_id   BIGINT NOT NULL REFERENCES autodev_doc(id) ON DELETE CASCADE,
    link_type   VARCHAR(20) NOT NULL DEFAULT 'mdlink',
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_id, target_id, link_type)
);

COMMENT ON TABLE autodev_doc_link IS '开发文档引用关系（双链/Markdown链接）';
CREATE INDEX idx_autodev_doc_link_source ON autodev_doc_link(source_id);
CREATE INDEX idx_autodev_doc_link_target ON autodev_doc_link(target_id);
