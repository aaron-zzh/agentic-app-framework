-- 聊天会话
CREATE TABLE sys_chat_session (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         INTEGER NOT NULL DEFAULT 0,
    org_id          BIGINT,
    workspace_id    BIGINT,
    title           VARCHAR(200),
    type            VARCHAR(30) NOT NULL DEFAULT 'LIVECHAT',
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    creator_id      BIGINT NOT NULL,
    create_by       BIGINT,
    create_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time     TIMESTAMP,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    remark          VARCHAR(500)
);

COMMENT ON TABLE sys_chat_session IS '聊天会话';
COMMENT ON COLUMN sys_chat_session.type IS '会话类型：LIVECHAT / AI / IM';
COMMENT ON COLUMN sys_chat_session.status IS '状态：ACTIVE / CLOSED';
COMMENT ON COLUMN sys_chat_session.creator_id IS '创建者用户 ID';

CREATE INDEX idx_sys_chat_session_creator ON sys_chat_session(creator_id) WHERE deleted = FALSE;
CREATE INDEX idx_sys_chat_session_type ON sys_chat_session(type) WHERE deleted = FALSE;

-- 聊天消息
CREATE TABLE sys_chat_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         INTEGER NOT NULL DEFAULT 0,
    org_id          BIGINT,
    workspace_id    BIGINT,
    session_id      BIGINT NOT NULL,
    sender_id       BIGINT NOT NULL,
    sender_type     VARCHAR(16) NOT NULL DEFAULT 'HUMAN',
    role            VARCHAR(20) NOT NULL DEFAULT 'user',
    content         TEXT NOT NULL,
    create_by       BIGINT,
    create_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by       BIGINT,
    update_time     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time     TIMESTAMP,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    remark          VARCHAR(500)
);

COMMENT ON TABLE sys_chat_message IS '聊天消息';
COMMENT ON COLUMN sys_chat_message.session_id IS '所属会话 ID';
COMMENT ON COLUMN sys_chat_message.sender_id IS '发送者 ID';
COMMENT ON COLUMN sys_chat_message.sender_type IS '发送者类型：HUMAN / AI';
COMMENT ON COLUMN sys_chat_message.role IS '消息角色：user / assistant / system';
COMMENT ON COLUMN sys_chat_message.content IS '消息内容';

CREATE INDEX idx_sys_chat_message_session ON sys_chat_message(session_id) WHERE deleted = FALSE;
CREATE INDEX idx_sys_chat_message_sender ON sys_chat_message(sender_id) WHERE deleted = FALSE;
