-- ============================================================
-- Content Studio 执行链路 Schema
-- ============================================================

CREATE TABLE cs_object_version (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version                  INTEGER        NOT NULL DEFAULT 0,
    org_id                   BIGINT,
    workspace_id             BIGINT,
    project_id               BIGINT         NOT NULL,
    object_id                BIGINT         NOT NULL,
    version_no               INTEGER        NOT NULL,
    status                   VARCHAR(32)    NOT NULL,
    content_payload          JSONB,
    asset_refs               JSONB,
    execution_run_id         BIGINT,
    summary                  VARCHAR(500),
    adopted_time             TIMESTAMP(6),
    adopted_by               BIGINT,
    superseded_by_version_id BIGINT,
    owner_id                 BIGINT,
    create_by                BIGINT,
    create_by_type           VARCHAR(16),
    create_time              TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by                BIGINT,
    update_by_type           VARCHAR(16),
    update_time              TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time              TIMESTAMP(6),
    deleted                  BOOLEAN        NOT NULL DEFAULT FALSE,
    remark                   VARCHAR(255)
);
COMMENT ON TABLE cs_object_version IS 'Content Studio 项目对象版本';
COMMENT ON COLUMN cs_object_version.version_no IS '对象内单调递增版本号';
COMMENT ON COLUMN cs_object_version.status IS '版本状态：candidate、adopted、rejected 或 superseded';
COMMENT ON COLUMN cs_object_version.content_payload IS '候选内容载荷 JSON';
COMMENT ON COLUMN cs_object_version.asset_refs IS '候选资产引用 JSON 数组';
COMMENT ON COLUMN cs_object_version.execution_run_id IS '产出该版本的执行记录 ID';
COMMENT ON COLUMN cs_object_version.superseded_by_version_id IS '取代当前版本的新版本 ID';
CREATE INDEX idx_cs_object_version_project ON cs_object_version (project_id);
CREATE INDEX idx_cs_object_version_object_status ON cs_object_version (object_id, status);
CREATE UNIQUE INDEX uk_cs_object_version_no_active
    ON cs_object_version (object_id, version_no) WHERE deleted = FALSE;

CREATE TABLE cs_execution_binding (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               INTEGER        NOT NULL DEFAULT 0,
    org_id                BIGINT,
    workspace_id          BIGINT,
    action_key            VARCHAR(100)   NOT NULL,
    project_type_code     VARCHAR(64),
    domain_extension_code VARCHAR(64),
    production_mode       VARCHAR(32),
    channel_code          VARCHAR(64),
    target_type           VARCHAR(32)    NOT NULL,
    target_ref            VARCHAR(200)   NOT NULL,
    binding_version       VARCHAR(32)    NOT NULL,
    priority              INTEGER        NOT NULL DEFAULT 0,
    confirmation_required BOOLEAN        NOT NULL DEFAULT TRUE,
    estimated_credits     NUMERIC(12,2),
    status                VARCHAR(32)    NOT NULL,
    owner_id              BIGINT,
    create_by             BIGINT,
    create_by_type        VARCHAR(16),
    create_time           TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by             BIGINT,
    update_by_type        VARCHAR(16),
    update_time            TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time           TIMESTAMP(6),
    deleted               BOOLEAN        NOT NULL DEFAULT FALSE,
    remark                VARCHAR(255)
);
COMMENT ON TABLE cs_execution_binding IS 'Content Studio 动作执行绑定';
COMMENT ON COLUMN cs_execution_binding.action_key IS '稳定业务动作键';
COMMENT ON COLUMN cs_execution_binding.project_type_code IS '项目类型编码，NULL 表示通配';
COMMENT ON COLUMN cs_execution_binding.domain_extension_code IS '行业扩展编码，NULL 表示通配';
COMMENT ON COLUMN cs_execution_binding.production_mode IS '生产模式，NULL 表示通配';
COMMENT ON COLUMN cs_execution_binding.channel_code IS '渠道编码，NULL 表示通配';
COMMENT ON COLUMN cs_execution_binding.target_type IS '执行目标类型：agent、tool 或 workflow';
COMMENT ON COLUMN cs_execution_binding.target_ref IS '执行目标稳定引用';
CREATE INDEX idx_cs_execution_binding_action_status
    ON cs_execution_binding (action_key, status);

UPDATE cs_project_object
SET object_type = 'canvas_board'
WHERE object_type = 'inspiration_board';
