-- =====================================================
-- 分销统计视图
-- =====================================================

-- 佣金每日发放趋势（按业务类型）
CREATE VIEW v_brokerage_record_daily AS
SELECT
    DATE_TRUNC('day', r.create_time)      AS stat_date,
    r.biz_type,
    r.status,
    COUNT(*)                              AS record_count,
    SUM(r.amount)                         AS total_amount,
    AVG(r.amount)                         AS avg_amount
FROM brokerage_record r
WHERE r.deleted = FALSE
GROUP BY DATE_TRUNC('day', r.create_time), r.biz_type, r.status;

COMMENT ON VIEW v_brokerage_record_daily IS '佣金流水每日统计（按业务类型+状态）';

-- 分销员成长趋势（每日新增）
CREATE VIEW v_brokerage_user_daily AS
SELECT
    DATE_TRUNC('day', u.brokerage_time)   AS stat_date,
    COUNT(*)                              AS new_brokers
FROM brokerage_user u
WHERE u.deleted = FALSE AND u.brokerage_enabled = TRUE AND u.brokerage_time IS NOT NULL
GROUP BY DATE_TRUNC('day', u.brokerage_time);

COMMENT ON VIEW v_brokerage_user_daily IS '分销员每日新增趋势';

-- 分销核心 KPI 汇总（单行，供仪表盘数字卡片使用）
CREATE VIEW v_brokerage_summary AS
SELECT
    COUNT(DISTINCT u.id)                                                        AS total_brokers,
    COUNT(DISTINCT CASE WHEN u.brokerage_enabled THEN u.id END)                AS active_brokers,
    COALESCE(SUM(CASE WHEN r.create_time >= DATE_TRUNC('month', NOW())
                       AND r.deleted = FALSE THEN r.amount END), 0)            AS month_amount,
    COUNT(DISTINCT CASE WHEN w.status = 'PENDING' AND w.deleted = FALSE
                         THEN w.id END)                                        AS pending_withdraws,
    COALESCE(SUM(ic.used_count), 0)                                            AS total_invite_binds
FROM brokerage_user u
LEFT JOIN brokerage_record r   ON r.contact_id = u.contact_id
LEFT JOIN brokerage_withdraw w ON w.contact_id = u.contact_id
LEFT JOIN brokerage_invite_code ic ON ic.contact_id = u.contact_id AND ic.deleted = FALSE
WHERE u.deleted = FALSE;

COMMENT ON VIEW v_brokerage_summary IS '分销核心 KPI 汇总（数字卡片用）';

CREATE INDEX IF NOT EXISTS idx_brokerage_record_daily
    ON brokerage_record(create_time, biz_type, status) WHERE deleted = FALSE;
CREATE INDEX IF NOT EXISTS idx_brokerage_user_time
    ON brokerage_user(brokerage_time, brokerage_enabled) WHERE deleted = FALSE;
