-- ==================== 分销员 ====================

CREATE TABLE brokerage_user (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             INTEGER      NOT NULL DEFAULT 0,
    org_id              BIGINT,
    workspace_id        BIGINT,
    contact_id          BIGINT       NOT NULL,
    referrer_contact_id BIGINT,
    referrer_bind_time  TIMESTAMP(6),
    brokerage_enabled   BOOLEAN      NOT NULL DEFAULT FALSE,
    brokerage_time      TIMESTAMP(6),
    balance             BIGINT       NOT NULL DEFAULT 0,
    frozen              BIGINT       NOT NULL DEFAULT 0,
    owner_id            BIGINT,
    create_by           BIGINT,
    create_by_type      VARCHAR(16),
    create_time         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by           BIGINT,
    update_by_type      VARCHAR(16),
    update_time         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time         TIMESTAMP(6),
    deleted             BOOLEAN      NOT NULL DEFAULT FALSE,
    remark              VARCHAR(255)
);

COMMENT ON TABLE brokerage_user IS '分销员';
COMMENT ON COLUMN brokerage_user.contact_id IS '关联 sys_contact.id';
COMMENT ON COLUMN brokerage_user.referrer_contact_id IS '推荐人 contact_id（上级分销员）';
COMMENT ON COLUMN brokerage_user.brokerage_enabled IS '是否有分销资格';
COMMENT ON COLUMN brokerage_user.balance IS '可用佣金（分）';
COMMENT ON COLUMN brokerage_user.frozen IS '冻结佣金（分）';

CREATE UNIQUE INDEX uk_brokerage_user_contact ON brokerage_user(contact_id) WHERE deleted = FALSE;
CREATE INDEX idx_brokerage_user_referrer ON brokerage_user(referrer_contact_id) WHERE deleted = FALSE;

-- ==================== 佣金规则 ====================

CREATE TABLE brokerage_rule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         INTEGER      NOT NULL DEFAULT 0,
    org_id          BIGINT,
    workspace_id    BIGINT,
    name            VARCHAR(64)  NOT NULL,
    biz_type        VARCHAR(32)  NOT NULL,
    biz_target_type VARCHAR(32),
    biz_target_id   VARCHAR(64),
    level1_rate     NUMERIC(5,4) NOT NULL DEFAULT 0,
    level2_rate     NUMERIC(5,4) NOT NULL DEFAULT 0,
    calc_base       VARCHAR(16)  NOT NULL DEFAULT 'AMOUNT',
    fixed_amount    BIGINT,
    frozen_days     INTEGER      NOT NULL DEFAULT 7,
    priority        INTEGER      NOT NULL DEFAULT 0,
    status          VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    owner_id        BIGINT,
    create_by       BIGINT,
    create_by_type  VARCHAR(16),
    create_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by       BIGINT,
    update_by_type  VARCHAR(16),
    update_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time     TIMESTAMP(6),
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    remark          VARCHAR(255)
);

COMMENT ON TABLE brokerage_rule IS '佣金规则';
COMMENT ON COLUMN brokerage_rule.biz_type IS '业务类型：ORDER/SUBSCRIBE/RECHARGE/INVITE';
COMMENT ON COLUMN brokerage_rule.biz_target_type IS '目标类型：PRODUCT/PLAN/PACKAGE，null=全部';
COMMENT ON COLUMN brokerage_rule.biz_target_id IS '具体目标ID，null=全部';
COMMENT ON COLUMN brokerage_rule.level1_rate IS '一级佣金比例（0.1000=10%）';
COMMENT ON COLUMN brokerage_rule.level2_rate IS '二级佣金比例';
COMMENT ON COLUMN brokerage_rule.calc_base IS '计算基准：AMOUNT=按金额比例 / FIXED=固定金额';
COMMENT ON COLUMN brokerage_rule.fixed_amount IS '固定佣金金额（分），calc_base=FIXED 时有效';
COMMENT ON COLUMN brokerage_rule.frozen_days IS '佣金冻结天数';
COMMENT ON COLUMN brokerage_rule.priority IS '优先级，数字越小越优先';
COMMENT ON COLUMN brokerage_rule.status IS 'ENABLED/DISABLED';

CREATE INDEX idx_brokerage_rule_biz ON brokerage_rule(biz_type, priority) WHERE deleted = FALSE AND status = 'ENABLED';

