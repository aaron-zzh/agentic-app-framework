-- AAF-032 #10 审批委托

CREATE TABLE sys_delegation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id       BIGINT,
    workspace_id BIGINT,
    delegator_id BIGINT       NOT NULL,
    delegate_id  BIGINT       NOT NULL,
    start_date   TIMESTAMP(6) NOT NULL,
    end_date     TIMESTAMP(6) NOT NULL,
    process_keys JSONB,
    status       VARCHAR(20)  NOT NULL DEFAULT 'active',
    version      INTEGER      NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE sys_delegation IS '审批委托';
COMMENT ON COLUMN sys_delegation.delegator_id IS '委托人 ID';
COMMENT ON COLUMN sys_delegation.delegate_id IS '代理人 ID';
COMMENT ON COLUMN sys_delegation.start_date IS '委托开始时间';
COMMENT ON COLUMN sys_delegation.end_date IS '委托结束时间';
COMMENT ON COLUMN sys_delegation.process_keys IS '适用流程 key 列表，null 表示全部流程';
COMMENT ON COLUMN sys_delegation.status IS '状态：active / expired / cancelled';

CREATE INDEX idx_delegation_delegator ON sys_delegation (delegator_id, status) WHERE deleted = false;
CREATE INDEX idx_delegation_delegate ON sys_delegation (delegate_id, status) WHERE deleted = false;
