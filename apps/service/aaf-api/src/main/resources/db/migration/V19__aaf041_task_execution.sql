-- 任务执行记录表
CREATE TABLE sys_task_execution (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name       VARCHAR(100) NOT NULL,
    task_type       VARCHAR(50) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'running',
    start_time      TIMESTAMP(6) NOT NULL,
    end_time        TIMESTAMP(6),
    duration_ms     BIGINT,
    error_message   TEXT,
    retry_count     INTEGER DEFAULT 0,
    create_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE sys_task_execution IS '任务执行记录';
COMMENT ON COLUMN sys_task_execution.task_name IS '任务名称';
COMMENT ON COLUMN sys_task_execution.task_type IS '任务类型：scheduled/async';
COMMENT ON COLUMN sys_task_execution.status IS '状态：running/success/failed/timeout';
COMMENT ON COLUMN sys_task_execution.start_time IS '开始时间';
COMMENT ON COLUMN sys_task_execution.end_time IS '结束时间';
COMMENT ON COLUMN sys_task_execution.duration_ms IS '执行耗时（毫秒）';
COMMENT ON COLUMN sys_task_execution.error_message IS '错误信息';
COMMENT ON COLUMN sys_task_execution.retry_count IS '重试次数';

CREATE INDEX idx_task_execution_name ON sys_task_execution(task_name);
CREATE INDEX idx_task_execution_status ON sys_task_execution(status);
CREATE INDEX idx_task_execution_start_time ON sys_task_execution(start_time);
