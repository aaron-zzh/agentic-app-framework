-- ============================================================
-- 消息反馈（单条消息点赞/踩/纠错）
-- 注：依赖 conversation_message，故定义在此（原 v2 因建表顺序无法引用）
-- ============================================================

CREATE TABLE conversation_message_feedback (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id      BIGINT       NOT NULL REFERENCES conversation_message(id),
    conversation_id BIGINT       NOT NULL,
    user_id         BIGINT       NOT NULL,
    -- 反馈类型：LIKE=点赞 / DISLIKE=踩 / CORRECTION=纠错
    feedback_type   VARCHAR(16)  NOT NULL,
    correction      TEXT,                           -- feedback_type=CORRECTION 时填写正确答案
    create_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (message_id, user_id)
);

COMMENT ON TABLE  conversation_message_feedback              IS '单条消息用户反馈：点赞/踩/纠错（append-only）';
COMMENT ON COLUMN conversation_message_feedback.feedback_type IS 'LIKE/DISLIKE/CORRECTION';
COMMENT ON COLUMN conversation_message_feedback.correction    IS '用户提供的正确答案，用于模型微调数据集收集';

CREATE INDEX idx_conv_msg_feedback_conv ON conversation_message_feedback(conversation_id);
CREATE INDEX idx_conv_msg_feedback_type ON conversation_message_feedback(feedback_type, create_time);
