-- ============================================================
-- 用户法律文档同意快照（合规追溯：服务条款 / 隐私政策）
-- 强耦合 doc_document，故与文档子域同表族
-- ============================================================

CREATE TABLE sys_user_consent (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER      NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    owner_id          BIGINT,
    user_id           BIGINT       NOT NULL REFERENCES sys_user(id),
    document_id       BIGINT       NOT NULL REFERENCES doc_document(id),
    document_version_id BIGINT     NOT NULL,
    document_type     VARCHAR(50)  NOT NULL,
    document_version  VARCHAR(50)  NOT NULL,
    consent_time      TIMESTAMP(6) NOT NULL,
    consent_ip        VARCHAR(50),
    source_app        VARCHAR(32),
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255),
    CONSTRAINT fk_user_consent_document_version
        FOREIGN KEY (document_version_id, document_id)
        REFERENCES doc_document_version(id, document_id) ON DELETE RESTRICT
);
COMMENT ON TABLE sys_user_consent IS '用户法律文档同意快照（精确冻结不可变正文版本）';
COMMENT ON COLUMN sys_user_consent.document_type IS 'legal-terms / legal-privacy';
COMMENT ON COLUMN sys_user_consent.document_version_id IS '用户同意时锁定的 doc_document_version.id';
COMMENT ON COLUMN sys_user_consent.document_version IS '不可变版本显示标签';

CREATE INDEX idx_user_consent_user_type
    ON sys_user_consent (user_id, document_type)
    WHERE deleted = FALSE;
CREATE INDEX idx_user_consent_document
    ON sys_user_consent (document_id)
    WHERE deleted = FALSE;
CREATE INDEX idx_user_consent_document_version
    ON sys_user_consent (document_version_id)
    WHERE deleted = FALSE;


