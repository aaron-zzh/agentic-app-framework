-- ============================================================
-- document 子域（业务文档，基础 CRUD）
-- ============================================================

CREATE TABLE doc_document (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version              INTEGER      NOT NULL DEFAULT 0,
    org_id               BIGINT,
    workspace_id         BIGINT,
    title                VARCHAR(200) NOT NULL,
    file_path            VARCHAR(500),
    source_file_id       BIGINT REFERENCES sys_file(id),
    current_version_id   BIGINT,
    published_version_id BIGINT,
    doc_type             VARCHAR(50)  NOT NULL DEFAULT 'spec',
    front_matter         JSONB,
    status               VARCHAR(20)  NOT NULL DEFAULT 'active',
    publish              VARCHAR(20)  NOT NULL DEFAULT 'draft',
    archived_at          TIMESTAMP(6),
    owner_id             BIGINT,
    create_by            BIGINT,
    create_by_type       VARCHAR(16),
    create_time          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by            BIGINT,
    update_by_type       VARCHAR(16),
    update_time          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time          TIMESTAMP(6),
    deleted              BOOLEAN      NOT NULL DEFAULT FALSE,
    remark               VARCHAR(255)
);

COMMENT ON TABLE doc_document IS '业务文档元数据；正文唯一存储于不可变版本表';
COMMENT ON COLUMN doc_document.current_version_id IS '当前正文版本；保存和恢复均通过创建新版本推进';
COMMENT ON COLUMN doc_document.published_version_id IS '当前已发布的精确正文版本';
COMMENT ON COLUMN doc_document.front_matter IS 'Front Matter 元数据（YAML 解析后的 JSON）';
COMMENT ON COLUMN doc_document.publish IS '发布状态：draft=草稿，published=已发布';

CREATE INDEX idx_doc_document_title_fts
    ON doc_document USING GIN (to_tsvector('simple', coalesce(title, '')));
CREATE INDEX idx_doc_document_publish ON doc_document (publish) WHERE deleted = FALSE;

CREATE TABLE doc_document_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER      NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    document_id       BIGINT       NOT NULL REFERENCES doc_document(id) ON DELETE RESTRICT,
    version_no        INTEGER      NOT NULL,
    parent_version_id BIGINT,
    title             VARCHAR(200) NOT NULL,
    content           TEXT         NOT NULL,
    format            VARCHAR(32)  NOT NULL,
    checksum          VARCHAR(64)  NOT NULL,
    source_type       VARCHAR(32)  NOT NULL DEFAULT 'MANUAL',
    source_ref        VARCHAR(255),
    change_summary    VARCHAR(500),
    owner_id          BIGINT,
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255),
    CONSTRAINT uk_doc_document_version_no UNIQUE (document_id, version_no),
    CONSTRAINT uk_doc_document_version_identity UNIQUE (id, document_id),
    CONSTRAINT fk_doc_document_version_parent
        FOREIGN KEY (parent_version_id, document_id)
        REFERENCES doc_document_version(id, document_id) ON DELETE RESTRICT,
    CONSTRAINT ck_doc_document_version_no CHECK (version_no > 0),
    CONSTRAINT ck_doc_document_version_parent
        CHECK (parent_version_id IS NULL OR parent_version_id <> id),
    CONSTRAINT ck_doc_document_version_format
        CHECK (format IN ('MARKDOWN', 'HTML', 'PLAIN_TEXT', 'JSON')),
    CONSTRAINT ck_doc_document_version_checksum
        CHECK (checksum ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_doc_document_version_source
        CHECK (source_type IN ('MANUAL', 'AIGC', 'IMPORT', 'RESTORE')),
    CONSTRAINT ck_doc_document_version_immutable CHECK (deleted = FALSE)
);

COMMENT ON TABLE doc_document_version IS '文档不可变全文快照；逐行 Diff 按需比较任意两个版本';
COMMENT ON COLUMN doc_document_version.parent_version_id IS '直接父版本；恢复历史内容时仍指向恢复操作前的当前版本';
COMMENT ON COLUMN doc_document_version.source_type IS '版本来源：MANUAL/AIGC/IMPORT/RESTORE';
COMMENT ON COLUMN doc_document_version.source_ref IS '来源业务引用，如 ExecutionRun、Task 或导入文件标识';
COMMENT ON COLUMN doc_document_version.change_summary IS '用户或生成链路提供的版本修改说明';

ALTER TABLE doc_document
    ADD CONSTRAINT fk_doc_document_current_version
        FOREIGN KEY (current_version_id, id)
        REFERENCES doc_document_version(id, document_id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_doc_document_published_version
        FOREIGN KEY (published_version_id, id)
        REFERENCES doc_document_version(id, document_id) ON DELETE RESTRICT;

CREATE INDEX idx_doc_document_current_version ON doc_document (current_version_id);
CREATE INDEX idx_doc_document_published_version ON doc_document (published_version_id);
CREATE INDEX idx_doc_document_version_parent ON doc_document_version (parent_version_id);
CREATE INDEX idx_doc_document_version_owner
    ON doc_document_version (owner_id, org_id, workspace_id) WHERE deleted = FALSE;
CREATE INDEX idx_doc_document_version_fts
    ON doc_document_version
    USING GIN (to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(content, '')));

CREATE FUNCTION reject_doc_document_version_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'doc_document_version is append-only; % is not allowed', TG_OP
        USING ERRCODE = '55000';
    RETURN OLD;
END;
$$;

CREATE TRIGGER trg_doc_document_version_immutable
BEFORE UPDATE OR DELETE ON doc_document_version
FOR EACH ROW
EXECUTE FUNCTION reject_doc_document_version_mutation();

COMMENT ON FUNCTION reject_doc_document_version_mutation() IS '拒绝原地修改或删除不可变文档版本';
COMMENT ON TRIGGER trg_doc_document_version_immutable ON doc_document_version IS '仅允许 INSERT 追加文档版本';

