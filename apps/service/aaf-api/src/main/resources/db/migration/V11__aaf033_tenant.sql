-- AAF-033 多租户：组织 + 组织成员

CREATE TABLE sys_organization (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT,
    workspace_id BIGINT,
    name         VARCHAR(100) NOT NULL,
    slug         VARCHAR(100) NOT NULL UNIQUE,
    type         VARCHAR(20)  NOT NULL DEFAULT 'team',
    owner_id     BIGINT       NOT NULL,
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE sys_organization IS '组织/租户';
COMMENT ON COLUMN sys_organization.type IS 'personal 个人工作空间 / team 团队组织';
COMMENT ON COLUMN sys_organization.slug IS '组织唯一标识（URL 友好）';
COMMENT ON COLUMN sys_organization.owner_id IS '组织所有者用户 ID';

CREATE TABLE sys_org_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT       NOT NULL,
    workspace_id BIGINT,
    user_id      BIGINT       NOT NULL,
    role         VARCHAR(20)  NOT NULL DEFAULT 'member',
    create_by    BIGINT,
    create_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE sys_org_member IS '组织成员';
COMMENT ON COLUMN sys_org_member.role IS 'owner 所有者 / admin 管理员 / member 成员';

CREATE UNIQUE INDEX uk_org_member_org_user ON sys_org_member (org_id, user_id) WHERE deleted = FALSE;

-- 为已有用户创建个人工作空间
INSERT INTO sys_organization (name, slug, type, owner_id, create_by)
SELECT nickname || '的空间', 'personal-' || id, 'personal', id, id
FROM sys_user WHERE deleted = FALSE;

-- 将用户加入自己的个人工作空间
INSERT INTO sys_org_member (org_id, user_id, role, create_by)
SELECT o.id, o.owner_id, 'owner', o.owner_id
FROM sys_organization o WHERE o.type = 'personal';
