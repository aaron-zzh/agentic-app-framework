    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER      NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    policy_id         BIGINT       NOT NULL,
    policy_version    BIGINT       NOT NULL,
    name              VARCHAR(128) NOT NULL,
    description       VARCHAR(512),
    condition_json    TEXT         NOT NULL,
    fact_schema_json  TEXT         NOT NULL,
    effect            VARCHAR(16)  NOT NULL,
    priority          INTEGER      NOT NULL,
    target_resource   VARCHAR(64)  NOT NULL,
    target_action     VARCHAR(64)  NOT NULL,
    lifecycle         VARCHAR(16)  NOT NULL,
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    owner_id          BIGINT,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255),
    CONSTRAINT uk_access_policy_snapshot UNIQUE (policy_id, policy_version),
    CONSTRAINT ck_access_policy_snapshot_lifecycle
        CHECK (lifecycle IN ('SHADOW', 'ENFORCE')),
    CONSTRAINT ck_access_policy_snapshot_effect
        CHECK (effect IN ('ALLOW', 'DENY', 'CHALLENGE'))
);

-- 旧启用策略只进入 SHADOW，避免未经重新编译和人工发布直接参与正式裁决。
INSERT INTO sys_access_policy_snapshot (
    policy_id,
    policy_version,
    name,
    description,
    condition_json,
    fact_schema_json,
    effect,
    priority,
    target_resource,
    target_action,
    lifecycle,
    org_id,
    workspace_id,
    create_by,
    create_by_type,
    owner_id
)
SELECT id,
       1,
       name,
       description,
       condition_json,
       fact_schema_json,
       effect,
       priority,
       target_resource,
       target_action,
       'SHADOW',
       org_id,
       workspace_id,
       create_by,
       create_by_type,
       owner_id
FROM sys_access_policy
WHERE lifecycle = 'SHADOW'
  AND deleted = FALSE;

-- 既有会话物化 OWNER 关系；新会话由 RelationPermissionWriter 在创建事务中同步写入。
INSERT INTO sys_permission_tuple (
    org_id,
    workspace_id,
    object_type,
    object_id,
    relation,
    subject_type,
    subject_id,
    subject_relation,
    granted_by,
    owner_id
)
SELECT conversation.org_id,
       conversation.workspace_id,
       'session',
       conversation.id::VARCHAR,
       'OWNER',
       'USER',
       conversation.creator_id::VARCHAR,
       '',
       'migration:v15',
       conversation.creator_id
FROM conversation
WHERE conversation.deleted = FALSE
ON CONFLICT (object_type, object_id, relation, subject_type, subject_id, subject_relation)
DO UPDATE SET org_id = EXCLUDED.org_id,
              workspace_id = EXCLUDED.workspace_id,
              granted_by = EXCLUDED.granted_by,
              owner_id = EXCLUDED.owner_id,
              deleted = FALSE,
              delete_time = NULL,
              update_time = CURRENT_TIMESTAMP
WHERE sys_permission_tuple.deleted = TRUE;

