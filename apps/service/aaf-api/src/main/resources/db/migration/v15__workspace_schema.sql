COMMENT ON TABLE sys_workspace_member IS '工作区成员：记录用户与工作区的归属关系，无角色字段（管理权限看工作区 create_by）';

CREATE UNIQUE INDEX uk_workspace_member_workspace_user ON sys_workspace_member (workspace_id, user_id) WHERE deleted = FALSE;

-- ============================================================
-- 存量无组织用户数据修复
--
-- 背景：B1 多组织 orgId fail-open 安全修复的前置条件——OrgFilterAspect 即将改为
-- fail-closed（orgId 缺失时拒绝而非静默放行），此前注册流程未接入
-- OrganizationService.createPersonalOrg，导致历史注册用户在 sys_org_member 中无任何记录。
-- 本脚本一次性为这些用户补建 personal 类型组织，保证 fail-closed 生效后不会把存量用户锁死。
--
-- 幂等：仅处理没有活动组织归属的用户，可安全重复执行。
-- ============================================================

-- 1) 优先恢复用户原有但已软删除的 personal 组织，避免旧全表唯一约束阻止重建
UPDATE sys_organization o
SET type = 'personal',
    owner_id = u.id,
    deleted = FALSE,
    delete_time = NULL,
    update_time = CURRENT_TIMESTAMP
FROM sys_user u
WHERE u.deleted = FALSE
  AND o.slug = 'personal-' || u.id
  AND o.deleted = TRUE
  AND NOT EXISTS (
      SELECT 1
      FROM sys_org_member m
      JOIN sys_organization active_org ON active_org.id = m.org_id AND active_org.deleted = FALSE
      WHERE m.user_id = u.id AND m.deleted = FALSE
  );

-- 2) 为仍无活动组织归属的用户补建 personal 组织
INSERT INTO sys_organization (name, slug, type, owner_id, create_by)
SELECT u.username, 'personal-' || u.id, 'personal', u.id, u.id
FROM sys_user u
WHERE u.deleted = FALSE
  AND NOT EXISTS (
      SELECT 1
      FROM sys_org_member m
      JOIN sys_organization o ON o.id = m.org_id AND o.deleted = FALSE
      WHERE m.user_id = u.id AND m.deleted = FALSE
  )
  AND NOT EXISTS (
      SELECT 1 FROM sys_organization o WHERE o.slug = 'personal-' || u.id AND o.deleted = FALSE
  );

-- 3) 补建活动 personal 组织的成员关联（owner）
INSERT INTO sys_org_member (org_id, user_id, role, create_by)
SELECT o.id, o.owner_id, 'owner', o.owner_id
FROM sys_organization o
WHERE o.type = 'personal'
  AND o.deleted = FALSE
  AND NOT EXISTS (
      SELECT 1 FROM sys_org_member m WHERE m.org_id = o.id AND m.user_id = o.owner_id AND m.deleted = FALSE
  );

