-- ============================================================
-- 工作区（Workspace）：组织内部的协作空间划分
--
-- 用户在所属组织下可自建多个工作区；权限模型不设独立角色层级，
-- create_by 即该工作区的管理者，拥有邀请/移除成员、改名、删除工作区等全部管理权限。
-- 组织成员不自动加入工作区，需显式邀请/加入（sys_workspace_member 记录归属关系）。
--
-- 详见设计文档 docs/design/apps/service/workspace-isolation.md。
-- ============================================================

CREATE TABLE sys_workspace (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      INTEGER      NOT NULL DEFAULT 0,
    org_id       BIGINT       NOT NULL,
    workspace_id BIGINT,
    name         VARCHAR(100) NOT NULL,
    slug         VARCHAR(100) NOT NULL,
    owner_id     BIGINT,
    create_by      BIGINT,
    create_by_type VARCHAR(16),
    create_time    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_by_type VARCHAR(16),
    update_time    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time  TIMESTAMP(6),
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    remark       VARCHAR(255)
);

COMMENT ON TABLE sys_workspace IS '工作区：组织内部的协作空间划分';
COMMENT ON COLUMN sys_workspace.slug IS 'URL 友好标识，组织内唯一';

CREATE UNIQUE INDEX uk_workspace_org_slug ON sys_workspace (org_id, slug) WHERE deleted = FALSE;

CREATE TABLE sys_workspace_member (
