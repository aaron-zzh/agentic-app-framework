-- 统一 L1-L4 授权运行时：策略生命周期/快照、授权审计和一次性 challenge。
-- Flyway locations 跨 db/migration 与 db/seed 全局排序；本脚本承接 v14，视图种子 v100-v103 后续执行。

ALTER TABLE sys_access_policy
    ADD COLUMN lifecycle VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    ADD COLUMN published_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN fact_schema_json TEXT NOT NULL DEFAULT '{}';

UPDATE sys_access_policy
SET condition_json = COALESCE(NULLIF(BTRIM(condition_json), ''), '{}'),
    fact_schema_json = '{}',
    target_resource = COALESCE(NULLIF(BTRIM(target_resource), ''), '*'),
    target_action = COALESCE(NULLIF(BTRIM(target_action), ''), '*'),
    lifecycle = CASE WHEN status = 1 THEN 'SHADOW' ELSE 'DRAFT' END,
    published_version = CASE WHEN status = 1 THEN 1 ELSE 0 END;

DROP INDEX IF EXISTS idx_sys_access_policy_target;

ALTER TABLE sys_access_policy
    ALTER COLUMN condition_json SET NOT NULL,
    ALTER COLUMN target_resource SET NOT NULL,
    ALTER COLUMN target_action SET NOT NULL,
    DROP COLUMN status,
    ADD CONSTRAINT ck_access_policy_lifecycle
        CHECK (lifecycle IN ('DRAFT', 'SHADOW', 'ENFORCE', 'DISABLED')),
    ADD CONSTRAINT ck_access_policy_effect
        CHECK (effect IN ('ALLOW', 'DENY', 'CHALLENGE'));

CREATE INDEX idx_sys_access_policy_runtime
    ON sys_access_policy (lifecycle, target_resource, target_action, priority)
    WHERE deleted = FALSE AND lifecycle IN ('SHADOW', 'ENFORCE');

