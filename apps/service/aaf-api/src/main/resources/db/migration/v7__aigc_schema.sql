CREATE TABLE aigc_assistant_blueprint_proposal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 0,
    org_id BIGINT NOT NULL,
    workspace_id BIGINT NOT NULL,
    planning_id VARCHAR(64) NOT NULL,
    proposal_id VARCHAR(128) NOT NULL,
    proposal_version INTEGER NOT NULL,
    proposal_hash VARCHAR(64),
    project_name VARCHAR(200) NOT NULL,
    creation_context JSONB NOT NULL,
    planning_instruction VARCHAR(4000) NOT NULL,
    assistant_id VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL,
    raw_proposal JSONB,
    normalized_snapshot JSONB,
    validation_result JSONB NOT NULL DEFAULT '{}'::jsonb,
    validator_version VARCHAR(32) NOT NULL,
    semantic_catalog_version VARCHAR(64),
    estimated_credits NUMERIC(12,2),
    source_task_id VARCHAR(128) NOT NULL,
    source_execution_id VARCHAR(128),
    confirmed_by BIGINT,
    confirmed_by_type VARCHAR(16),
    confirmed_time TIMESTAMP(6),
    confirmation_receipt_hash VARCHAR(64),
    expires_at TIMESTAMP(6) NOT NULL,
    linked_project_id BIGINT REFERENCES aigc_project(id) ON DELETE RESTRICT,
    owner_id BIGINT NOT NULL,
    create_by BIGINT,
    create_by_type VARCHAR(16),
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_by_type VARCHAR(16),
    update_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time TIMESTAMP(6),
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    remark VARCHAR(255),
    CONSTRAINT ck_aigc_assistant_blueprint_status CHECK (
        status IN ('PLANNING', 'AWAITING_CONFIRMATION', 'CONFIRMED', 'EXPIRED',
                   'SUPERSEDED', 'MATERIALIZED', 'FAILED', 'CANCELED')),
    CONSTRAINT ck_aigc_assistant_blueprint_version CHECK (proposal_version >= 1),
    CONSTRAINT ck_aigc_assistant_blueprint_hash CHECK (
        proposal_hash IS NULL OR proposal_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_aigc_assistant_blueprint_semantic_hash CHECK (
        semantic_catalog_version IS NULL OR semantic_catalog_version ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_aigc_assistant_blueprint_receipt_hash CHECK (
        confirmation_receipt_hash IS NULL OR confirmation_receipt_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_aigc_assistant_blueprint_payload CHECK (
        (status = 'PLANNING'
         AND proposal_hash IS NULL
         AND raw_proposal IS NULL
         AND normalized_snapshot IS NULL
         AND source_execution_id IS NULL
         AND confirmed_time IS NULL)
        OR
        (status = 'AWAITING_CONFIRMATION'
         AND proposal_hash IS NOT NULL
         AND raw_proposal IS NOT NULL
         AND normalized_snapshot IS NOT NULL
         AND semantic_catalog_version IS NOT NULL
         AND source_execution_id IS NOT NULL
         AND confirmed_time IS NULL)
        OR
        (status IN ('CONFIRMED', 'MATERIALIZED')
         AND proposal_hash IS NOT NULL
         AND raw_proposal IS NOT NULL
         AND normalized_snapshot IS NOT NULL
         AND semantic_catalog_version IS NOT NULL
         AND source_execution_id IS NOT NULL
         AND confirmed_by IS NOT NULL
         AND confirmed_by_type IS NOT NULL
         AND confirmed_time IS NOT NULL
         AND confirmation_receipt_hash IS NOT NULL)
        OR status IN ('EXPIRED', 'SUPERSEDED', 'FAILED', 'CANCELED')),
    CONSTRAINT ck_aigc_assistant_blueprint_link CHECK (
        (status = 'MATERIALIZED' AND linked_project_id IS NOT NULL)
        OR (status <> 'MATERIALIZED' AND linked_project_id IS NULL))
);
COMMENT ON TABLE aigc_assistant_blueprint_proposal IS 'Assistant 生成项目结构的独立版本化 Proposal；不复用项目内容生成 Proposal';
COMMENT ON COLUMN aigc_assistant_blueprint_proposal.creation_context IS '启动规划时冻结的用户创建表单事实；修订版本沿用且最终物化以此为权威';
COMMENT ON COLUMN aigc_assistant_blueprint_proposal.source_task_id IS '服务端预计算并在 Task 创建前绑定的 canonical Task 身份；Tool 只按 InvocationContext.taskId 解析';
COMMENT ON COLUMN aigc_assistant_blueprint_proposal.normalized_snapshot IS '经共享 Normalizer/Validator 生成的 AigcProjectBlueprintSnapshotPayload';
COMMENT ON COLUMN aigc_assistant_blueprint_proposal.linked_project_id IS '物化核心事务内回填；同一 Proposal 只允许关联一个项目';
