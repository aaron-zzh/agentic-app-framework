    -- 项目范围（受信）
    project_scope JSONB,

    -- 状态：PENDING（待触发）/ DISPATCHING（触发中）/ DEFERRED（等待当前任务）/ TRIGGERED（已触发）/ CANCELLED（已取消）/ FAILED（失败）
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',

    -- 调度控制
    next_attempt_at TIMESTAMPTZ,
    claim_fence VARCHAR(64),

    -- 关联的 canonical Task
    linked_task_id VARCHAR(128),

    -- 失败信息
    last_error TEXT,
    fail_count INT NOT NULL DEFAULT 0,

    -- 乐观锁
    version INT NOT NULL DEFAULT 0,

    -- 审计
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    delete_time TIMESTAMPTZ,

    CONSTRAINT fk_project FOREIGN KEY (project_id) REFERENCES aigc_project(id) ON DELETE CASCADE
);

