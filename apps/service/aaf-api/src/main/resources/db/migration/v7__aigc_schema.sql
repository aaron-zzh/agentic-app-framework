CREATE INDEX idx_project_schedule_project ON aigc_project_schedule(project_id) WHERE deleted = FALSE;
CREATE INDEX idx_project_schedule_owner ON aigc_project_schedule(owner_id) WHERE deleted = FALSE;
CREATE INDEX idx_project_schedule_execute_at ON aigc_project_schedule(execute_at) WHERE deleted = FALSE AND status IN ('PENDING', 'DEFERRED');
CREATE INDEX idx_project_schedule_status ON aigc_project_schedule(status) WHERE deleted = FALSE;
CREATE INDEX idx_project_schedule_next_attempt ON aigc_project_schedule(next_attempt_at) WHERE deleted = FALSE AND status IN ('PENDING', 'DEFERRED');

