-- ============================================================
-- 知识库
-- ============================================================

CREATE TABLE ai_knowledge_base (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version         INTEGER      NOT NULL DEFAULT 0,
    org_id          BIGINT,
    workspace_id    BIGINT,
    name            VARCHAR(200) NOT NULL,
    description     VARCHAR(1000),
    embedding_model VARCHAR(100),
    chunk_strategy  VARCHAR(50),
    chunk_size      INTEGER          DEFAULT 512,
    chunk_overlap   INTEGER          DEFAULT 64,
    status          INTEGER      NOT NULL DEFAULT 0,
    auto_inject     BOOLEAN      NOT NULL DEFAULT FALSE,
    create_by       BIGINT,
    create_by_type  VARCHAR(16),
    create_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by       BIGINT,
    update_by_type  VARCHAR(16),
    update_time     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    owner_id        BIGINT,
    delete_time     TIMESTAMP(6),
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    remark          TEXT
);

COMMENT ON TABLE ai_knowledge_base IS '知识库';

CREATE TABLE ai_knowledge_document (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER      NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    knowledge_base_id BIGINT       NOT NULL REFERENCES ai_knowledge_base(id),
    title             VARCHAR(500) NOT NULL,
    file_path         VARCHAR(1000),
    file_type         VARCHAR(50),
    file_size         BIGINT,
    content_hash      VARCHAR(64),
    status            INTEGER      NOT NULL DEFAULT 0,
    error_message     VARCHAR(2000),
    chunk_count       INTEGER          DEFAULT 0,
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    owner_id          BIGINT,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    remark            TEXT
);

COMMENT ON TABLE ai_knowledge_document IS '知识库文档';
CREATE INDEX idx_ai_knowledge_document_base ON ai_knowledge_document(knowledge_base_id);

CREATE TABLE ai_knowledge_chunk (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id       BIGINT       NOT NULL REFERENCES ai_knowledge_document(id),
    knowledge_base_id BIGINT       NOT NULL REFERENCES ai_knowledge_base(id),
    content           TEXT         NOT NULL,
    chunk_index       INTEGER      NOT NULL DEFAULT 0,
    metadata          JSONB,
    token_count       INTEGER          DEFAULT 0,
    created_at        TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE ai_knowledge_chunk IS '知识库文本块';
CREATE INDEX idx_ai_knowledge_chunk_document ON ai_knowledge_chunk(document_id);
CREATE INDEX idx_ai_knowledge_chunk_base ON ai_knowledge_chunk(knowledge_base_id);

CREATE TABLE ai_knowledge_embedding (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    content           TEXT,
    metadata          JSONB,
    embedding         vector(1536),
    chunk_id          BIGINT       REFERENCES ai_knowledge_chunk(id),
    knowledge_base_id BIGINT       REFERENCES ai_knowledge_base(id),
    model_name        VARCHAR(50),
    created_at        TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE ai_knowledge_embedding IS '知识库向量嵌入（兼容 Spring AI VectorStore）';
COMMENT ON COLUMN ai_knowledge_embedding.embedding IS '固定 1536 维：写入的嵌入须由 1536 维模型生成；更换嵌入维度需迁移本列与索引';
CREATE INDEX idx_ai_knowledge_embedding_chunk ON ai_knowledge_embedding(chunk_id);
CREATE INDEX idx_ai_knowledge_embedding_base ON ai_knowledge_embedding(knowledge_base_id);
CREATE INDEX idx_ai_knowledge_embedding_hnsw ON ai_knowledge_embedding
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

-- ============================================================
-- 记忆
-- ============================================================

CREATE TABLE ai_memory_atom (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id          BIGINT                   NOT NULL,
    scope            VARCHAR(20)              NOT NULL,
    content          TEXT                     NOT NULL,
    embedding        vector(1536),
    event_time       TIMESTAMP WITH TIME ZONE NOT NULL,
    valid_from       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    valid_to         TIMESTAMP WITH TIME ZONE,
    weight           DOUBLE PRECISION         NOT NULL DEFAULT 0.5,
    access_count     INTEGER                  NOT NULL DEFAULT 0,
    last_accessed_at TIMESTAMP WITH TIME ZONE,
    tags             TEXT[],
    metadata         JSONB,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE ai_memory_atom IS '记忆原子：scope = short_term / long_term / episodic / procedural';
COMMENT ON COLUMN ai_memory_atom.embedding IS '固定 1536 维：须与知识库嵌入使用同一 1536 维模型，便于记忆/知识跨域检索';
CREATE INDEX idx_ai_memory_atom_user_scope  ON ai_memory_atom(user_id, scope);
CREATE INDEX idx_ai_memory_atom_user_event  ON ai_memory_atom(user_id, event_time DESC);
CREATE INDEX idx_ai_memory_atom_user_weight ON ai_memory_atom(user_id, weight DESC);
CREATE INDEX idx_ai_memory_atom_tags        ON ai_memory_atom USING GIN(tags);
CREATE INDEX idx_ai_memory_atom_embedding   ON ai_memory_atom
    USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);

CREATE TABLE ai_memory_relation (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_id      UUID             NOT NULL REFERENCES ai_memory_atom(id) ON DELETE CASCADE,
    target_id      UUID             NOT NULL REFERENCES ai_memory_atom(id) ON DELETE CASCADE,
    relation_type  VARCHAR(50)      NOT NULL,
    weight         DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    edge_text      TEXT,
    edge_embedding vector(1536),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE ai_memory_relation IS '记忆原子间关系（用于 BundleSearch 图路由）';
CREATE INDEX idx_ai_memory_relation_source ON ai_memory_relation(source_id);
CREATE INDEX idx_ai_memory_relation_target ON ai_memory_relation(target_id);


