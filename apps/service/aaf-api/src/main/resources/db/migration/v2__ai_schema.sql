-- ============================================================
-- AI 基础设施 Schema
-- 包含：模型管理、Prompt模板、Token用量、记忆、Agent、Assistant、Team
-- ============================================================

-- ============================================================
-- 模型管理
-- ============================================================

CREATE TABLE ai_model (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             INTEGER          NOT NULL DEFAULT 0,
    org_id              BIGINT,
    workspace_id        BIGINT,
    model_id            VARCHAR(64)      NOT NULL UNIQUE,
    display_name        VARCHAR(128)     NOT NULL,
    provider            VARCHAR(32)      NOT NULL,
    provider_type       VARCHAR(32)      NOT NULL DEFAULT 'OPENAI_COMPAT',
    model_name          VARCHAR(128)     NOT NULL,
    base_url            VARCHAR(512),
    api_key_encrypted   VARCHAR(1024),
    temperature         DOUBLE PRECISION,
    max_tokens          INTEGER,
    context_window      INTEGER,
    enabled             BOOLEAN          NOT NULL DEFAULT TRUE,
    capabilities        VARCHAR(256),
    input_price_per_k   NUMERIC(10, 6),
    output_price_per_k  NUMERIC(10, 6),
    fallback_model_id   VARCHAR(64),
    sort_order          INTEGER              DEFAULT 100,
    create_by           BIGINT,
    create_time         TIMESTAMP(6),
    update_by           BIGINT,
    update_time         TIMESTAMP(6),
    delete_time         TIMESTAMP(6),
    deleted             BOOLEAN          NOT NULL DEFAULT FALSE,
    remark              TEXT
);

COMMENT ON TABLE ai_model IS 'AI 模型配置';
COMMENT ON COLUMN ai_model.provider_type     IS '协议类型：OPENAI_COMPAT / ANTHROPIC / OLLAMA';
COMMENT ON COLUMN ai_model.capabilities      IS '能力标记：CHAT,VISION,EMBEDDING,IMAGE_GEN,AUDIO,RERANK';
COMMENT ON COLUMN ai_model.input_price_per_k IS '输入 Token 单价（元/千Token）';
COMMENT ON COLUMN ai_model.output_price_per_k IS '输出 Token 单价（元/千Token）';

CREATE TABLE ai_model_preference (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     INTEGER      NOT NULL DEFAULT 0,
    scope       VARCHAR(16)  NOT NULL,
    scope_id    BIGINT,
    capability  VARCHAR(32)  NOT NULL,
    model_id    VARCHAR(64)  NOT NULL,
    create_by   BIGINT,
    create_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by   BIGINT,
    update_time TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time TIMESTAMP(6),
    deleted     BOOLEAN      NOT NULL DEFAULT FALSE,
    remark      VARCHAR(255),
    CONSTRAINT uq_model_preference UNIQUE (scope, scope_id, capability)
);

COMMENT ON TABLE ai_model_preference IS '模型偏好配置';
COMMENT ON COLUMN ai_model_preference.scope      IS 'USER=用户级别 / SYSTEM=系统默认';
COMMENT ON COLUMN ai_model_preference.scope_id   IS '用户ID（scope=USER时），SYSTEM时为null';
COMMENT ON COLUMN ai_model_preference.capability IS '能力类型：CHAT/EMBEDDING/IMAGE_GEN/SPEECH_ASR等';

CREATE TABLE ai_prompt_template (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version          INTEGER      NOT NULL DEFAULT 0,
    org_id           BIGINT,
    workspace_id     BIGINT,
    name             VARCHAR(128) NOT NULL,
    template_version INTEGER          NOT NULL DEFAULT 1,
    content          TEXT         NOT NULL,
    description      VARCHAR(512),
    variables        TEXT,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    category         VARCHAR(64),
    create_by        BIGINT,
    create_time      TIMESTAMP(6),
    update_by        BIGINT,
    update_time      TIMESTAMP(6),
    delete_time      TIMESTAMP(6),
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    remark           TEXT,
    UNIQUE (name, template_version)
);

COMMENT ON TABLE ai_prompt_template IS 'Prompt 模板';

-- ============================================================
-- Token 用量
-- ============================================================

CREATE TABLE ai_token_usage (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    conversation_id   VARCHAR(64),
    model_id          VARCHAR(64)  NOT NULL,
    prompt_tokens     BIGINT       NOT NULL,
    completion_tokens BIGINT       NOT NULL,
    total_tokens      BIGINT       NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE ai_token_usage IS 'Token 用量记录';
CREATE INDEX idx_ai_token_usage_user_created  ON ai_token_usage (user_id, created_at);
CREATE INDEX idx_ai_token_usage_model_created ON ai_token_usage (model_id, created_at);

-- ============================================================
-- 记忆
-- ============================================================

CREATE TABLE ai_long_term_memory (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT           NOT NULL,
    content          TEXT             NOT NULL,
    source_id        VARCHAR(128),
    memory_type      VARCHAR(32)      NOT NULL,
    importance       DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    last_accessed_at TIMESTAMP(6),
    access_count     INTEGER              NOT NULL DEFAULT 0,
    event_time       TIMESTAMP(6),
    created_at       TIMESTAMP(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE ai_long_term_memory IS '长期记忆';
CREATE INDEX idx_ai_long_term_memory_user ON ai_long_term_memory (user_id, importance DESC);

CREATE TABLE ai_procedural_memory (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version       INTEGER          NOT NULL DEFAULT 0,
    org_id        BIGINT,
    workspace_id  BIGINT,
    user_id       BIGINT,
    task_type     VARCHAR(64)      NOT NULL,
    category      VARCHAR(64),
    title         VARCHAR(256)     NOT NULL,
    content       TEXT             NOT NULL,
    success_count INTEGER              NOT NULL DEFAULT 0,
    use_count     INTEGER              NOT NULL DEFAULT 0,
    quality_score DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    create_by     BIGINT,
    create_time   TIMESTAMP(6),
    update_by     BIGINT,
    update_time   TIMESTAMP(6),
    delete_time   TIMESTAMP(6),
    deleted       BOOLEAN          NOT NULL DEFAULT FALSE,
    remark        TEXT
);

COMMENT ON TABLE ai_procedural_memory IS '程序性记忆';
CREATE INDEX idx_ai_procedural_memory_user ON ai_procedural_memory (user_id, category);

