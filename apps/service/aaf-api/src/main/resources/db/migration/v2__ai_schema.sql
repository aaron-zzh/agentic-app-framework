CREATE TABLE media_asset (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER        NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    name              VARCHAR(200)   NOT NULL,
    type              VARCHAR(20)    NOT NULL,
    url               VARCHAR(1000)  NOT NULL,
    thumbnail_url     VARCHAR(1000),
    size              BIGINT,
    width             INTEGER,
    height            INTEGER,
    duration          NUMERIC(10,2),
    generation_params JSONB,
    tags              VARCHAR(500),
    category_id       BIGINT,
    user_id           BIGINT         NOT NULL,
    create_by         BIGINT,
    create_time       TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_time       TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN        NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255)
);

COMMENT ON TABLE media_asset IS 'AIGC 素材库';
COMMENT ON COLUMN media_asset.type IS '素材类型：IMAGE/VIDEO/AUDIO/MODEL_3D';
COMMENT ON COLUMN media_asset.generation_params IS 'AI 生成参数（prompt、模型等）';

CREATE INDEX idx_media_asset_user_id ON media_asset (user_id);
