CREATE TABLE cs_brand_profile (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           INTEGER        NOT NULL DEFAULT 0,
    org_id            BIGINT,
    workspace_id      BIGINT,
    name              VARCHAR(200)   NOT NULL,
    kind              VARCHAR(32)    NOT NULL,
    industry          VARCHAR(64),
    logo_url          VARCHAR(1000),
    positioning       VARCHAR(1000),
    audience          VARCHAR(1000),
    tone_of_voice     VARCHAR(1000),
    visual_style      VARCHAR(1000),
    disclaimer        VARCHAR(1000),
    forbidden_items   VARCHAR(1000),
    rules             JSONB,
    profile_assets    JSONB,
    profile_version   VARCHAR(32),
    status            VARCHAR(32)    NOT NULL,
    user_id           BIGINT,
    owner_id          BIGINT,
    create_by         BIGINT,
    create_by_type    VARCHAR(16),
    create_time       TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by         BIGINT,
    update_by_type    VARCHAR(16),
    update_time       TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time       TIMESTAMP(6),
    deleted           BOOLEAN        NOT NULL DEFAULT FALSE,
    remark            VARCHAR(255)
);
COMMENT ON TABLE cs_brand_profile IS 'Content Studio 品牌/IP 资料';
COMMENT ON COLUMN cs_brand_profile.kind IS '资料类型：企业品牌、子品牌、产品线或个人 IP';
COMMENT ON COLUMN cs_brand_profile.rules IS '品牌规则 JSON 快照';
COMMENT ON COLUMN cs_brand_profile.profile_assets IS '品牌资料关联资产 JSON';
CREATE INDEX idx_cs_brand_profile_owner ON cs_brand_profile (owner_id);
CREATE INDEX idx_cs_brand_profile_kind ON cs_brand_profile (kind);

