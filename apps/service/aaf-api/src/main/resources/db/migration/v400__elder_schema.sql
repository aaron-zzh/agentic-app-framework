-- ==================== 长者档案 elder_profile ====================

CREATE TABLE elder_profile (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             INTEGER      NOT NULL DEFAULT 0,
    org_id              BIGINT,
    workspace_id        BIGINT,
    user_id             BIGINT,
    full_name           VARCHAR(100) NOT NULL,
    gender              VARCHAR(16),
    birth_date          DATE,
    id_card_no          VARCHAR(64),
    mobile              VARCHAR(32),
    address             VARCHAR(500),
    living_arrangement  VARCHAR(32)  NOT NULL DEFAULT 'ALONE',
    preferred_name      VARCHAR(100),
    preferences         TEXT,
    taboos              TEXT,
    status              VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    camera_consent      BOOLEAN      NOT NULL DEFAULT FALSE,
    camera_consent_by   BIGINT,
    camera_consent_at   TIMESTAMP(6),
    owner_id            BIGINT,
    create_by           BIGINT,
    create_by_type      VARCHAR(16),
    create_time         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by           BIGINT,
    update_by_type      VARCHAR(16),
    update_time         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time         TIMESTAMP(6),
    deleted             BOOLEAN      NOT NULL DEFAULT FALSE,
    remark              VARCHAR(255)
);

COMMENT ON TABLE elder_profile IS '长者档案';
COMMENT ON COLUMN elder_profile.user_id IS '可选关联的 AAF 用户 ID';
COMMENT ON COLUMN elder_profile.id_card_no IS '身份证件号，敏感字段';
COMMENT ON COLUMN elder_profile.living_arrangement IS 'ALONE/WITH_FAMILY/WITH_CAREGIVER';
COMMENT ON COLUMN elder_profile.camera_consent IS '是否已同意摄像头与预警功能';

CREATE UNIQUE INDEX uk_elder_profile_user
    ON elder_profile(user_id) WHERE user_id IS NOT NULL AND deleted = FALSE;
CREATE UNIQUE INDEX uk_elder_profile_id_card
    ON elder_profile(id_card_no) WHERE id_card_no IS NOT NULL AND deleted = FALSE;
CREATE INDEX idx_elder_profile_status
    ON elder_profile(status) WHERE deleted = FALSE;
CREATE INDEX idx_elder_profile_org_workspace
    ON elder_profile(org_id, workspace_id) WHERE deleted = FALSE;

