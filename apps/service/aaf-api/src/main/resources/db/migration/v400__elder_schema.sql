-- ==================== 预警事件 elder_alert ====================

CREATE TABLE elder_alert (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               INTEGER      NOT NULL DEFAULT 0,
    org_id                BIGINT,
    workspace_id          BIGINT,
    device_id             BIGINT       NOT NULL,
    elder_id              BIGINT       NOT NULL,
    event_id              VARCHAR(100) NOT NULL,
    alert_type            VARCHAR(32)  NOT NULL,
    level                 VARCHAR(16)  NOT NULL,
    status                VARCHAR(16)  NOT NULL DEFAULT 'TRIGGERED',
    zone                  VARCHAR(32)  NOT NULL DEFAULT 'OTHER',
    confidence            NUMERIC(5,4),
    payload               JSONB        NOT NULL DEFAULT '{}'::jsonb,
    device_occurred_at    TIMESTAMP(6) NOT NULL,
    received_at           TIMESTAMP(6) NOT NULL,
    late                  BOOLEAN      NOT NULL DEFAULT FALSE,
    next_action_at        TIMESTAMP(6),
    claimed_by            BIGINT,
    claimed_at            TIMESTAMP(6),
    acknowledged_at       TIMESTAMP(6),
    resolved_at           TIMESTAMP(6),
    owner_id              BIGINT,
    create_by             BIGINT,
    create_by_type        VARCHAR(16),
    create_time           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by             BIGINT,
    update_by_type        VARCHAR(16),
    update_time           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time           TIMESTAMP(6),
    deleted               BOOLEAN      NOT NULL DEFAULT FALSE,
    remark                VARCHAR(255),
    CONSTRAINT ck_elder_alert_confidence
        CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);

COMMENT ON TABLE elder_alert IS '养老安全预警事件，长期保留';
COMMENT ON COLUMN elder_alert.event_id IS '设备事件幂等键，后端生成事件也使用唯一值';
COMMENT ON COLUMN elder_alert.payload IS '附加语义数据，不得包含图片、视频或人脸特征';
COMMENT ON COLUMN elder_alert.late IS '是否为设备恢复联网后的晚到事件';

CREATE UNIQUE INDEX uk_elder_alert_device_event
    ON elder_alert(device_id, event_id) WHERE deleted = FALSE;
CREATE INDEX idx_elder_alert_elder_time
    ON elder_alert(elder_id, device_occurred_at DESC) WHERE deleted = FALSE;
CREATE INDEX idx_elder_alert_open
    ON elder_alert(status, level, device_occurred_at DESC)
    WHERE deleted = FALSE AND status IN ('TRIGGERED', 'NOTIFYING', 'ACKED');
CREATE INDEX idx_elder_alert_next_action
    ON elder_alert(next_action_at)
    WHERE deleted = FALSE AND next_action_at IS NOT NULL;

