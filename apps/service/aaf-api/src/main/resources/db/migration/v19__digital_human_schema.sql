-- ============================================================
-- 数字人实体表
-- ============================================================

CREATE TABLE digital_human (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version              INTEGER                  NOT NULL DEFAULT 0,
    org_id               BIGINT,
    workspace_id         BIGINT,

    -- 基础信息
    name                 VARCHAR(255)             NOT NULL,
    description          TEXT,
    tags                 JSONB,

    -- 形象资产（仅 2D）
    avatar_image_url     VARCHAR(512)             NOT NULL,
    appearance           JSONB,
    -- appearance 结构示例:
    -- {
    --   "age": 25,
    --   "gender": "female",
    --   "style": "商务装",
    --   "prompt": "25岁职业女性，短发，商务装，温柔微笑"
    -- }

    -- 音色配置（阿里云预设）
    voice_config         JSONB                    NOT NULL,
    -- voice_config 结构示例:
    -- {
    --   "provider": "aliyun",
    --   "presetVoiceId": "aijia",
    --   "voiceName": "艾佳",
    --   "speechRate": 0,
    --   "pitchRate": 0,
    --   "volume": 50
    -- }

    -- 大模型配置
    model_config         JSONB,
    -- model_config 结构示例:
    -- {
    --   "provider": "anthropic",
    --   "model": "claude-sonnet-5",
    --   "temperature": 0.7,
    --   "maxTokens": 2000,
    --   "systemPrompt": "你是一位专业的营销顾问..."
    -- }

    -- 双向关联助理
    assistant_id         BIGINT,
    sync_model_config    BOOLEAN                  NOT NULL DEFAULT FALSE,

    -- 使用统计
    video_count          INTEGER                  NOT NULL DEFAULT 0,
    total_duration       INTEGER                  NOT NULL DEFAULT 0,
    credits_consumed     INTEGER                  NOT NULL DEFAULT 0,
    last_used_at         TIMESTAMP(6),

    -- 状态（无审批流程）
    status               VARCHAR(32)              NOT NULL DEFAULT 'active',
    generation_source    VARCHAR(32),
    aigc_project_id      BIGINT,

    -- 审计字段
    owner_id             BIGINT,
    create_by            BIGINT,
    create_by_type       VARCHAR(16),
    create_time          TIMESTAMP(6)             NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by            BIGINT,
    update_by_type       VARCHAR(16),
    update_time          TIMESTAMP(6)             NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time          TIMESTAMP(6),
    deleted              BOOLEAN                  NOT NULL DEFAULT FALSE,
    remark               TEXT,

    -- 约束
    CONSTRAINT chk_digital_human_status CHECK (status IN ('active', 'archived')),
    CONSTRAINT chk_digital_human_source CHECK (generation_source IS NULL OR generation_source IN ('aigc_project'))
);

COMMENT ON TABLE digital_human IS '数字人实体表';
COMMENT ON COLUMN digital_human.owner_id IS '创建者用户ID（数据归属者）';
COMMENT ON COLUMN digital_human.org_id IS '组织ID（支持组织共享）';
COMMENT ON COLUMN digital_human.name IS '数字人名称';
COMMENT ON COLUMN digital_human.description IS '数字人描述';
COMMENT ON COLUMN digital_human.tags IS '标签数组（营销、客服等，JSON 数组）';
COMMENT ON COLUMN digital_human.avatar_image_url IS '数字人头像图片URL';
COMMENT ON COLUMN digital_human.appearance IS '形象信息（年龄、性别、风格、提示词）';
COMMENT ON COLUMN digital_human.voice_config IS '音色配置（阿里云预设音色）';
COMMENT ON COLUMN digital_human.model_config IS '大模型配置';
COMMENT ON COLUMN digital_human.assistant_id IS '关联的助理ID（双向绑定）';
COMMENT ON COLUMN digital_human.sync_model_config IS '是否同步助理的模型配置';
COMMENT ON COLUMN digital_human.video_count IS '生成视频数量';
COMMENT ON COLUMN digital_human.total_duration IS '累计视频时长（秒）';
COMMENT ON COLUMN digital_human.credits_consumed IS '累计消耗积分';
COMMENT ON COLUMN digital_human.last_used_at IS '最后使用时间';
COMMENT ON COLUMN digital_human.status IS '状态（active: 激活, archived: 归档）';
COMMENT ON COLUMN digital_human.generation_source IS '生成来源（aigc_project）';
COMMENT ON COLUMN digital_human.aigc_project_id IS '关联的AIGC项目ID';

-- 索引
CREATE INDEX idx_digital_human_owner ON digital_human(owner_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_org ON digital_human(org_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_status ON digital_human(status) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_assistant ON digital_human(assistant_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_created_at ON digital_human(create_time DESC) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_tags ON digital_human USING GIN(tags) WHERE deleted = FALSE;

