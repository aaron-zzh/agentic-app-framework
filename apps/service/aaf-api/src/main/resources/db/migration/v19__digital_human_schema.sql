COMMENT ON COLUMN digital_human_preset_voice.description IS '音色描述';
COMMENT ON COLUMN digital_human_preset_voice.gender IS '性别（male/female）';
COMMENT ON COLUMN digital_human_preset_voice.sample_audio_url IS '试听音频URL';
COMMENT ON COLUMN digital_human_preset_voice.provider IS '提供商（aliyun）';
COMMENT ON COLUMN digital_human_preset_voice.external_voice_id IS '第三方音色ID（阿里云音色ID）';
COMMENT ON COLUMN digital_human_preset_voice.is_active IS '是否启用';
COMMENT ON COLUMN digital_human_preset_voice.display_order IS '显示顺序';

-- 索引
CREATE INDEX idx_digital_human_preset_voice_provider ON digital_human_preset_voice(provider) WHERE is_active = TRUE AND deleted = FALSE;
CREATE INDEX idx_digital_human_preset_voice_display_order ON digital_human_preset_voice(display_order) WHERE is_active = TRUE AND deleted = FALSE;

