-- ============================================================
-- 积分消耗记录表
-- ============================================================

CREATE TABLE digital_human_credit_consumption (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version              INTEGER                  NOT NULL DEFAULT 0,

    -- 所属关系
    org_id               BIGINT,
    workspace_id         BIGINT,

    -- 关联资源
    digital_human_id     BIGINT,
    project_id           BIGINT                   NOT NULL,

    -- 操作信息
    operation            VARCHAR(64)              NOT NULL,
    credits_consumed     INTEGER                  NOT NULL,

    -- 成本明细
    breakdown            JSONB,
    -- breakdown 结构示例:
    -- {
    --   "apiProvider": "hyperframes",
    --   "apiCost": 7.30,
    --   "duration": 60,
    --   "sceneCount": 4,
    --   "elements": ["background_music", "text_overlay"]
    -- }

    -- 审计字段
    owner_id             BIGINT,
    create_by            BIGINT,
    create_by_type       VARCHAR(16),
    create_time          TIMESTAMP(6)             NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by            BIGINT,
    update_by_type       VARCHAR(16),
    update_time          TIMESTAMP(6)             NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delete_time          TIMESTAMP(6),
    deleted              BOOLEAN                  NOT NULL DEFAULT FALSE,
    remark               TEXT,

    -- 约束
    CONSTRAINT chk_digital_human_credit_consumption_operation CHECK (operation IN ('avatar_generation', 'simple_video', 'complex_video')),
    CONSTRAINT fk_digital_human_credit_consumption_digital_human FOREIGN KEY (digital_human_id) REFERENCES digital_human(id) ON DELETE SET NULL
);

COMMENT ON TABLE digital_human_credit_consumption IS '数字人积分消耗记录表';
COMMENT ON COLUMN digital_human_credit_consumption.owner_id IS '消费用户ID（数据归属者）';
COMMENT ON COLUMN digital_human_credit_consumption.org_id IS '组织ID';
COMMENT ON COLUMN digital_human_credit_consumption.digital_human_id IS '关联的数字人ID';
COMMENT ON COLUMN digital_human_credit_consumption.project_id IS '关联的项目ID';
COMMENT ON COLUMN digital_human_credit_consumption.operation IS '操作类型（avatar_generation/simple_video/complex_video）';
COMMENT ON COLUMN digital_human_credit_consumption.credits_consumed IS '消耗的积分数';
COMMENT ON COLUMN digital_human_credit_consumption.breakdown IS '成本明细（API提供商、费用、时长、场景数等）';

-- 索引
CREATE INDEX idx_digital_human_credit_consumption_owner ON digital_human_credit_consumption(owner_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_credit_consumption_org ON digital_human_credit_consumption(org_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_credit_consumption_digital_human ON digital_human_credit_consumption(digital_human_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_credit_consumption_project ON digital_human_credit_consumption(project_id) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_credit_consumption_created_at ON digital_human_credit_consumption(create_time DESC) WHERE deleted = FALSE;
CREATE INDEX idx_digital_human_credit_consumption_operation ON digital_human_credit_consumption(operation) WHERE deleted = FALSE;

