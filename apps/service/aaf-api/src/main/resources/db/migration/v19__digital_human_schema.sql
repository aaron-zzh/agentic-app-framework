    -- 基础信息
    name                 VARCHAR(128)             NOT NULL,
    description          TEXT,
    gender               VARCHAR(16),

    -- 音频样本
    sample_audio_url     VARCHAR(512),

    -- 第三方配置
    provider             VARCHAR(64)              NOT NULL DEFAULT 'aliyun',
    external_voice_id    VARCHAR(128)             NOT NULL,

