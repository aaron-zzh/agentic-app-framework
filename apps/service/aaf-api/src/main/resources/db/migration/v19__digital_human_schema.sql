-- ============================================================
-- 统计视图
-- ============================================================

CREATE OR REPLACE VIEW v_digital_human_stats AS
SELECT
    dh.id,
    dh.name,
    dh.avatar_image_url,
    dh.owner_id,
    dh.org_id,
    dh.video_count,
    dh.total_duration,
    dh.credits_consumed,
    dh.last_used_at,
    dh.status,
    dh.create_time,
    COUNT(DISTINCT cc.id) AS consumption_records_count,
    COALESCE(SUM(cc.credits_consumed), 0) AS verified_credits_consumed
FROM digital_human dh
LEFT JOIN digital_human_credit_consumption cc ON dh.id = cc.digital_human_id AND cc.deleted = FALSE
WHERE dh.deleted = FALSE
GROUP BY
    dh.id, dh.name, dh.avatar_image_url, dh.owner_id, dh.org_id,
    dh.video_count, dh.total_duration, dh.credits_consumed, dh.last_used_at,
    dh.status, dh.create_time;

COMMENT ON VIEW v_digital_human_stats IS '数字人统计视图（含积分消耗验证）';

