-- ============================================================
-- 命名说明：本文件所有 tenant_id 列（VARCHAR）承载业务系统 sys_organization.id（org_id）的字符串投影，
-- 与 org_id 是同一个隔离维度，不是并行的第二套多租户机制。领域层用 tenant_id 而非直接依赖 org_id: BIGINT，
-- 是为了不让 intelligent.* 五层架构领域模型依赖具体业务模块的持久化类型；取值处见各 Controller 的
-- new TenantId(orgId.toString())。详见 intelligent.shared.id.StableId.TenantId 的类型注释。
-- ============================================================

