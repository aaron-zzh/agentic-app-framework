--                       决定后由 ToolApprovalGrantListener 回写会话级工具授权
-- 此表取代原内存版 HumanApprovalService：内存态在重启/多实例下丢失，且旧链无任何消费方，
-- 审批建出来永远无人可处理，而卡片已推给用户。

